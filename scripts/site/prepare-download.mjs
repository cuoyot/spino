// Split a large signed artifact into static assets without changing its public URL.
// Usage: node scripts/site/prepare-download.mjs <local-file> <public-filename>
import {readFile,writeFile,mkdir,rm} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import existing from './download-parts.mjs';
const [source,name]=process.argv.slice(2);
if(!source||!/^spino-[\w.-]+\.apk$/.test(name||''))throw Error('Expected a local APK and a SPino public APK filename.');
const data=await readFile(source),sha=bytes=>createHash('sha256').update(bytes).digest('hex'),root=new URL('./downloads/',import.meta.url);
await mkdir(root,{recursive:true});
if(data.length<=25*1024*1024){await writeFile(new URL(name,root),data);delete existing['/downloads/'+name];}
else{
 const parts=[];await mkdir(new URL('parts/',root),{recursive:true});
 for(let offset=0,n=0;offset<data.length;offset+=20*1024*1024,n++){
  const bytes=data.subarray(offset,offset+20*1024*1024),part=`parts/${name}.${String(n).padStart(3,'0')}.bin`;
  await writeFile(new URL(part,root),bytes);parts.push({path:'/downloads/'+part,bytes:bytes.length,sha256:sha(bytes)});
 }
 existing['/downloads/'+name]={bytes:data.length,sha256:sha(data),parts};
 await rm(new URL(name,root),{force:true});
}
await writeFile(new URL('download-parts.mjs',import.meta.url),'// Generated by prepare-download.mjs. Keys are the public download URLs.\nexport default '+JSON.stringify(existing,null,2)+';\n');
console.log(JSON.stringify({file:name,bytes:data.length,sha256:sha(data),parts:existing['/downloads/'+name]?.parts.length||0}));
