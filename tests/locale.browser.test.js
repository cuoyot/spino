import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { openBrowser } from './browser.js';

test('Edit profile applies and retains language across notebook, catalogue and managed reader', { timeout: 90000 }, async t => {
  const { send, evaluate, url, errors } = await openBrowser(t, { companion: true, language: 'en-US' });
  await send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true });
  await send('Page.navigate', { url });
  const wait = expression => evaluate(`new Promise((resolve,reject)=>{let i=0;const timer=setInterval(()=>{if(${expression}){clearInterval(timer);resolve();}else if(++i>750){clearInterval(timer);reject(Error('timeout: '+${JSON.stringify(expression)}));}},20);})`);
  const click = selector => evaluate(`document.querySelector(${JSON.stringify(selector)}).click()`);
  await wait(`document.querySelector('.cp-profile-nav')`);
  assert.equal(await evaluate(`document.documentElement.lang`), 'en');
  await click('.cp-profile-nav');
  assert.equal(await evaluate(`document.querySelector('#app-shell h1').textContent`), 'Profile');
  await click('[data-action=profile-edit]');
  assert.equal(await evaluate(`document.querySelector('[name=language]').value`), 'en');
  await evaluate(`document.querySelector('[name=language]').value='es'`);
  await click('[data-action=close-dialog]');
  assert.equal(await evaluate(`document.documentElement.lang`), 'en', 'cancel leaves the language unchanged');
  await click('[data-action=profile-edit]');
  await evaluate(`window.originalPut=IDBObjectStore.prototype.put;IDBObjectStore.prototype.put=function(value,key){if(this.name==='state'&&key==='current'&&value.preferences?.language==='es'){const tx=this.transaction;queueMicrotask(()=>tx.abort());}return originalPut.apply(this,arguments);}`);
  await evaluate(`{const f=document.querySelector('#profile-identity-form');f.elements.language.value='es';f.elements.name.value='English Name';f.requestSubmit();}`);
  await wait(`document.querySelector('#cp-form-error')?.textContent`);
  assert.equal(await evaluate(`document.documentElement.lang`), 'en', 'a failed save leaves the applied language unchanged');
  await evaluate(`IDBObjectStore.prototype.put=window.originalPut;document.querySelector('#profile-identity-form').requestSubmit()`);
  await wait(`!document.querySelector('#cp-dialog').open`);
  assert.equal(await evaluate(`document.documentElement.lang`), 'es');
  assert.equal(await evaluate(`document.querySelector('#app-shell h1').textContent`), 'Perfil');
  assert.equal(await evaluate(`document.querySelector('.cp-profile-identity h2').textContent`), 'English Name');
  await click('[data-action=profile-edit]');
  assert.equal(await evaluate(`document.querySelector('[name=language]').value`), 'es');
  await mkdir('artifacts/review', { recursive: true });
  const shot = await send('Page.captureScreenshot', { format: 'png' });
  await writeFile('artifacts/review/profile-language-es.png', Buffer.from(shot.data, 'base64'));
  await click('[data-action=close-dialog]');
  await send('Page.reload');
  await wait(`document.querySelector('.cp-profile-nav')`);
  assert.equal(await evaluate(`document.documentElement.lang`), 'es', 'saved choice overrides an English device');
  assert.equal(await evaluate(`__sr.settings.lang`), 'es');
  await click('[data-action=piano]');
  await click('[data-action=repertoire]');
  assert.match(await evaluate(`document.querySelector('#app-shell').innerText`), /Tu repertorio/);
  assert.doesNotMatch(await evaluate(`document.querySelector('#app-shell').innerText`), /Find, organize|Collection|Trash|Sort by/);
  await click('[data-action=new-work]');
  assert.match(await evaluate(`document.querySelector('#cp-dialog').innerText`), /Etiquetas/);
  assert.doesNotMatch(await evaluate(`document.querySelector('#cp-dialog').innerText`), /Unknown|Tags|Import score/);
  await click('[data-action=close-dialog]');
  await click('[data-action=piano]');
  await click('[data-action=catalog]');
  await wait(`document.querySelector('#library-search')`);
  assert.doesNotMatch(await evaluate(`document.querySelector('#app-shell').innerText`), /Available scores|No scores|Review edition|Downloadable editions|Pending analysis/);
  await click('[data-action=home]');
  await click('.cp-nav [data-action=practice]');
  await click('[data-action=prepare][data-id=reading]');
  await evaluate(`document.querySelector('#prepare-form').requestSubmit()`);
  await wait(`document.querySelector('[data-action=open-reader]')`);
  await click('[data-action=open-reader]');
  assert.equal(await evaluate(`__sr.settings.lang`), 'es');
  assert.equal(await evaluate(`document.querySelector('#practice-finish').textContent`), 'Terminar');
  await click('#practice-return');
  await click('[data-action=session-end]');
  assert.equal(await evaluate(`document.querySelector('#cp-dialog [data-action=discard-session]').textContent`), 'Terminar sin guardar');
  await click('[data-action=close-dialog]');
  await click('[data-action=leave-session]');
  await click('.cp-profile-nav');
  await click('[data-action=profile-edit]');
  await evaluate(`{const f=document.querySelector('#profile-identity-form');f.elements.language.value='en';f.requestSubmit();}`);
  await wait(`!document.querySelector('#cp-dialog').open`);
  assert.equal(await evaluate(`document.querySelector('#app-shell h1').textContent`), 'Profile');
  await click('[data-action=resume-session]');
  await click('[data-action=open-reader]');
  assert.equal(await evaluate(`__sr.settings.lang`), 'en', 'resumed practice follows the profile language');
  assert.equal(await evaluate(`document.querySelector('#practice-finish').textContent`), 'Finish');
  assert.deepEqual(errors, []);
});

test('notebooks saved before language preferences retain their Spanish UI and user content', { timeout: 60000 }, async t => {
  const { send, evaluate, url } = await openBrowser(t, { companion: true, language: 'en' });
  await send('Page.navigate', { url });
  const wait = expression => evaluate(`new Promise((resolve,reject)=>{let i=0;const timer=setInterval(()=>{if(${expression}){clearInterval(timer);resolve();}else if(++i>500){clearInterval(timer);reject(Error('timeout'));}},20);})`);
  await wait(`document.querySelector('.cp-profile-nav')`);
  await evaluate(`new Promise((resolve,reject)=>{const r=indexedDB.open('cuaderno-piano',1);r.onsuccess=()=>{const db=r.result,tx=db.transaction('state','readwrite'),q=tx.objectStore('state').get('current');q.onsuccess=()=>{const d=q.result;delete d.preferences.language;d.preferences.name='My original name';tx.objectStore('state').put(d,'current');};tx.oncomplete=()=>{db.close();resolve();};tx.onerror=()=>reject(tx.error);};})`);
  await send('Page.reload');
  await wait(`document.querySelector('.cp-profile-nav')`);
  assert.equal(await evaluate(`document.documentElement.lang`), 'es');
  await evaluate(`document.querySelector('.cp-profile-nav').click()`);
  assert.equal(await evaluate(`document.querySelector('.cp-profile-identity h2').textContent`), 'My original name');
});

test('Spanish manual practice keeps numeric field identifiers and user feedback intact', { timeout: 60000 }, async t => {
  const { send, evaluate, url, errors } = await openBrowser(t, { companion: true });
  await send('Page.navigate', { url });
  const wait = expression => evaluate(`new Promise((resolve,reject)=>{let i=0;const timer=setInterval(()=>{if(${expression}){clearInterval(timer);resolve();}else if(++i>500){clearInterval(timer);reject(Error('timeout'));}},20);})`);
  await wait(`document.querySelector('.cp-profile-nav')`);
  await evaluate(`document.querySelector('[data-action=calendar]').click();document.querySelector('[data-action=add-on-day]').click();document.querySelector('[data-action=manual-session]').click()`);
  await evaluate(`{const f=document.querySelector('#cp-dialog form');f.elements.minutes.value='37';f.elements.title.value='My English practice';f.elements.notes.value='Keep this text unchanged';f.requestSubmit();}`);
  await wait(`!document.querySelector('#cp-dialog').open`);
  const saved = await evaluate(`new Promise(resolve=>{const r=indexedDB.open('cuaderno-piano',1);r.onsuccess=()=>{const q=r.result.transaction('state').objectStore('state').get('current');q.onsuccess=()=>{resolve(q.result.sessions[0]);r.result.close();};};})`);
  assert.equal(saved.elapsedMs, 37 * 60000);
  assert.equal(saved.title, 'My English practice');
  assert.equal(saved.notes, 'Keep this text unchanged');
  assert.equal(saved.manual, true);
  assert.deepEqual(errors, []);
});
