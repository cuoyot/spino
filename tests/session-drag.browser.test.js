import assert from 'node:assert/strict';
import { test } from 'node:test';
import { openBrowser } from './browser.js';
import { emptyData, beginSession, block, finishBlock } from '../src/companion/model.js';

test('long press moves and bins remaining blocks without losing performed work', { timeout: 40000 }, async t => {
  const { send, evaluate, errors, url } = await openBrowser(t, { companion: true });
  const wait = condition => evaluate('new Promise((resolve,reject)=>{let n=0;const timer=setInterval(()=>{if(' + condition + '){clearInterval(timer);resolve();}else if(++n>300){clearInterval(timer);reject(Error(' + JSON.stringify(condition) + '));}},20);})');
  const data = emptyData(); data.preferences.language = 'en';
  await send('Page.navigate', { url }); await wait('document.querySelector(".cp-today")');
  data.active = beginSession({ title: 'Gesture fixture', context: 'piano', blocks: ['done','current','later'].map(id => block('free', { id, minutes: 10 })) });
  data.active.elapsedMs = data.active.blockElapsedMs = 60000; finishBlock(data.active);
  data.active.elapsedMs += 480000; data.active.blockElapsedMs = 480000;
  await evaluate('new Promise(resolve=>{const r=indexedDB.open("cuaderno-piano",1);r.onsuccess=()=>{const tx=r.result.transaction("state","readwrite");tx.objectStore("state").put(' + JSON.stringify(data) + ',"current");tx.oncomplete=()=>{r.result.close();resolve();};};})');
  await send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true });
  await send('Emulation.setTouchEmulationEnabled', { enabled: true });
  await send('Page.reload'); await wait('document.querySelector("[data-action=resume-session]")');
  await evaluate('document.querySelector("[data-action=resume-session]").click()');
  const point = selector => evaluate('(()=>{const r=document.querySelector(' + JSON.stringify(selector) + ').getBoundingClientRect();return{x:r.x+r.width/2,y:r.y+r.height/2}})()');
  const touch = (type, p) => send('Input.dispatchTouchEvent', { type, touchPoints: p ? [{ ...p, id: 1 }] : [] });
  const order = () => evaluate('[...document.querySelectorAll("[data-session-block]")].map(e=>e.dataset.sessionBlock)');
  const hold = async id => {
    await evaluate('document.querySelector("[data-session-block=' + id + ']").scrollIntoView({block:"center"})');
    await new Promise(resolve => setTimeout(resolve, 250));
    await touch('touchStart', await point('[data-session-block=' + id + '] .cp-session-block-copy'));
    await wait('!!document.querySelector(".cp-session-drag-ghost")');
  };
  assert.equal(await evaluate('document.querySelector("[data-session-block=done] [data-session-options]")'), null);
  const start = await point('[data-session-block=current] .cp-session-block-copy');
  await touch('touchStart', start);
  await touch('touchMove', { x: start.x, y: start.y - 65 }); await touch('touchEnd');
  await wait('document.querySelector(".cp-page").scrollTop > 0');
  assert.deepEqual(await order(), ['done','current','later']);
  assert.equal(await evaluate('!!document.querySelector(".cp-session-drag-ghost")'), false);
  await hold('current'); await touch('touchCancel');
  await wait('!document.querySelector(".cp-session-drag-ghost")');
  assert.deepEqual(await order(), ['done','current','later']);
  await hold('current');
  const target = await point('[data-session-block=later]');
  await touch('touchMove', { x: 350, y: target.y + 12 });
  await wait('document.querySelector("[data-session-block=later]").classList.contains("is-drop-after")');
  await touch('touchEnd');
  await wait('document.querySelector("[data-session-block=later][aria-current=step]")');
  assert.deepEqual(await order(), ['done','later','current']);
  assert.match(await evaluate('document.querySelector("[data-session-block=current]").textContent'), /Practised 8:00/);
  await hold('current');
  await touch('touchMove', await point('[data-session-bin]'));
  await wait('document.querySelector("[data-session-bin]").classList.contains("is-over")');
  await touch('touchEnd');
  await wait('!document.querySelector("[data-session-block=current]")');
  const saved = await evaluate('new Promise(resolve=>{const r=indexedDB.open("cuaderno-piano",1);r.onsuccess=()=>{const q=r.result.transaction("state").objectStore("state").get("current");q.onsuccess=()=>{resolve(q.result);r.result.close();};};})');
  assert.equal(saved.active.elapsedMs, 540000);
  assert.equal(saved.active.results.find(r => r.block.id === 'current').elapsedMs, 480000);
  assert.deepEqual(saved.active.results[0], data.active.results[0]);
  await hold('later');
  assert.equal(await evaluate('document.querySelector("[data-session-bin]").disabled'), true);
  await touch('touchCancel');
  await evaluate('document.querySelector("[data-session-options]").click()');
  assert.equal(await evaluate('document.querySelector("[data-session-menu]").hidden'), false);
  assert.equal(await evaluate('document.querySelector("[data-action=session-block-remove]").disabled'), true);
  assert.deepEqual(errors, []);
});
