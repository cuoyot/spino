export const CATALAN = Object.fromEntries(entries.trim().split('\n').map(line => {
  const split = line.indexOf('|'); return [line.slice(0, split), line.slice(split + 1)];
}));
const escapePattern = value => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const templates = Object.entries(CATALAN).filter(([key]) => key.includes('{')).map(([key, translation]) => {
  const names = [...key.matchAll(/\{(\w+)\}/g)].map(match => match[1]);
  return { pattern: new RegExp('^' + key.split(/\{\w+\}/).map(escapePattern).join('(.*?)') + '$'), names, translation };
});

export function catalan(value) {
  if (typeof value !== 'string') return value;
  if (Object.hasOwn(CATALAN, value)) return CATALAN[value];
  const trimmed = value.trim();
  if (Object.hasOwn(CATALAN, trimmed)) return value.replace(trimmed, CATALAN[trimmed]);
  // Translate only supplied interface fragments, not the rendered DOM or notebook.
  if (/<[^>]*>/.test(value)) return value.split(/(<[^>]*>)/g).map(part => part.startsWith('<') ? part.replace(/(placeholder|aria-label|title)="([^"]*)"/g, (_, attr, text) => `${attr}="${catalan(text)}"`) : catalan(part)).join('');
  for (const { pattern, names, translation } of templates) {
    const match = value.match(pattern);
    if (match) return translation.replace(/\{(\w+)\}/g, (_, name) => {
      const parameter = match[names.indexOf(name) + 1];
      return ['tool', 'orientation', 'cause', 'extra'].includes(name) ? CATALAN[parameter] ?? parameter : parameter;
    });
  }
  for (const prefix of ['Edit ', 'Move or remove ', 'Duration for ', 'Suggested minutes for ', 'Block ', 'Finger ']) {
    if (value.startsWith(prefix)) return ({'Edit ':'Editar ', 'Move or remove ':'Moure o eliminar ', 'Duration for ':'Durada de ', 'Suggested minutes for ':'Minuts orientatius de ', 'Block ':'Bloc ', 'Finger ':'Dit '})[prefix] + value.slice(prefix.length);
  }
  return value;
}
export function catalanCopy(value) {
  if (typeof value === 'string') return catalan(value);
  if (Array.isArray(value)) return value.join(',') === 'M,T,W,T,F,S,S' ? ['dl.', 'dt.', 'dc.', 'dj.', 'dv.', 'ds.', 'dg.'] : value.map(catalanCopy);
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, catalanCopy(v)]));
  return value;
}
