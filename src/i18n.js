let lang = 'en';

export function languageForLocale(locale = '') {
  const l = locale.toLowerCase().slice(0, 2);
  return STRINGS[l] ? l : l === 'ca' || l === 'gl' ? 'es' : 'en';
}

export function setLanguage(l) {
  lang = STRINGS[l] ? l : 'en';
  document.documentElement.lang = lang;
}

export function t(key, vars = {}) {
  const s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

// Translate native/plugin error messages we know about
export function tError(message = '') {
  const known = {
    'Bluetooth is off': 'bleOff',
    'Bluetooth LE is unavailable': 'bleUnavailable',
    'Bluetooth permission denied': 'blePerm',
    'Bluetooth scan is only available in the Android app': 'bleAndroidOnly',
  };
  return known[message] ? t(known[message]) : message;
}

// Fill every element marked with data-i18n / data-i18n-aria / data-i18n-title
export function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => el.setAttribute('aria-label', t(el.dataset.i18nAria)));
  root.querySelectorAll('[data-i18n-title]').forEach((el) => el.setAttribute('title', t(el.dataset.i18nTitle)));
}
